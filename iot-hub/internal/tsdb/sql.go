// Open connects to a database by URL:
//
//	sqlite:path/to/file.db   (or a bare path ending in .db)
//	postgres://user:pass@host/db
func Open(ctx context.Context, url string) (DB, error) {
	switch {
	case strings.HasPrefix(url, "postgres://"), strings.HasPrefix(url, "postgresql://"):
		return openSQL(ctx, "pgx", url, true)
	case strings.HasPrefix(url, "sqlite:"):
		return openSQLite(ctx, strings.TrimPrefix(url, "sqlite:"))
	case strings.HasSuffix(url, ".db"), strings.HasSuffix(url, ".sqlite"):
		return openSQLite(ctx, url)
	}
	return nil, fmt.Errorf("unsupported database URL %q (use sqlite:<file> or postgres://...)", url)
}

func openSQLite(ctx context.Context, path string) (DB, error) {
	// WAL lets dashboard reads run during writes; NORMAL sync is safe with
	// WAL (a power cut can lose the last commit, never corrupt the file).
	// cache_size is per connection, in KiB when negative.
	dsn := "file:" + path + "?_txlock=immediate" +
		"&_pragma=journal_mode(WAL)&_pragma=synchronous(NORMAL)" +
		"&_pragma=busy_timeout(5000)&_pragma=cache_size(-2048)&_pragma=temp_store(MEMORY)"
	return openSQL(ctx, "sqlite", dsn, false)
}

type sqlDB struct {
	db *sql.DB
	pg bool

	mu     sync.Mutex
	series map[string]int64 // sensor\x00field -> id
}

func openSQL(ctx context.Context, driver, dsn string, pg bool) (*sqlDB, error) {
	db, err := sql.Open(driver, dsn)
	if err != nil {
		return nil, err
	}
	db.SetMaxOpenConns(4)
	db.SetMaxIdleConns(2)
	s := &sqlDB{db: db, pg: pg, series: map[string]int64{}}
	if err := s.migrate(ctx); err != nil {
		db.Close()
		return nil, err
	}
	return s, nil
}

func (s *sqlDB) migrate(ctx context.Context) error {
	id, noRowID := "INTEGER PRIMARY KEY", " WITHOUT ROWID"
	if s.pg {
		id, noRowID = "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY", ""
	}
	ddl := []string{
		`CREATE TABLE IF NOT EXISTS series (id ` + id + `, sensor TEXT NOT NULL, field TEXT NOT NULL, UNIQUE (sensor, field))`,
		// Clustered on (series, ts): a range query is one sequential scan.
		`CREATE TABLE IF NOT EXISTS readings (series BIGINT NOT NULL, ts BIGINT NOT NULL, value DOUBLE PRECISION, text TEXT, PRIMARY KEY (series, ts))` + noRowID,
		`CREATE TABLE IF NOT EXISTS rollup_1m (series BIGINT NOT NULL, minute BIGINT NOT NULL, n BIGINT NOT NULL, sum DOUBLE PRECISION NOT NULL, sumsq DOUBLE PRECISION NOT NULL, min DOUBLE PRECISION NOT NULL, max DOUBLE PRECISION NOT NULL, PRIMARY KEY (series, minute))` + noRowID,
		`CREATE TABLE IF NOT EXISTS anomalies (id TEXT PRIMARY KEY, sensor TEXT NOT NULL, field TEXT NOT NULL, kind TEXT NOT NULL, start_ts BIGINT NOT NULL, end_ts BIGINT, value DOUBLE PRECISION, score DOUBLE PRECISION, message TEXT)`,
		`CREATE INDEX IF NOT EXISTS anomalies_start ON anomalies (start_ts)`,
		`CREATE INDEX IF NOT EXISTS anomalies_sensor ON anomalies (sensor, start_ts)`,
	}
	for _, q := range ddl {
		if _, err := s.db.ExecContext(ctx, q); err != nil {
			return fmt.Errorf("migrate: %w", err)
		}
	}
	return nil
}

// q rewrites ? placeholders to $n for PostgreSQL.
func (s *sqlDB) q(query string) string {
	if !s.pg {
		return query
	}
	var b strings.Builder
	n := 0
	for i := 0; i < len(query); i++ {
		if query[i] == '?' {
			n++
			b.WriteByte('$')
			b.WriteString(strconv.Itoa(n))
		} else {
			b.WriteByte(query[i])
		}
	}
	return b.String()
}

func (s *sqlDB) Close() error { return s.db.Close() }

type querier interface {
	ExecContext(context.Context, string, ...any) (sql.Result, error)
	QueryRowContext(context.Context, string, ...any) *sql.Row
}

func seriesKey(sensor, field string) string { return sensor + "\x00" + field }

// lookupID returns the id for sensor/field, or 0 if it has never been
// written. Only committed ids enter the cache.
func (s *sqlDB) lookupID(ctx context.Context, x querier, sensor, field string) (int64, error) {
	key := seriesKey(sensor, field)
	s.mu.Lock()
	id, ok := s.series[key]
	s.mu.Unlock()
	if ok {
		return id, nil
	}
	err := x.QueryRowContext(ctx, s.q(`SELECT id FROM series WHERE sensor = ? AND field = ?`), sensor, field).Scan(&id)
	if errors.Is(err, sql.ErrNoRows) {
		return 0, nil
	}
	if err != nil {
		return 0, err
	}
	if x == querier(s.db) {
		s.mu.Lock()
		s.series[key] = id
		s.mu.Unlock()
	}
	return id, nil
}

type agg struct {
	n              int64
	sum, sumsq     float64
	min, max       float64
	series, minute int64
}

const rowsPerStmt = 250 // 4 params/row: far below SQLite's and Postgres' limits

func (s *sqlDB) WritePoints(ctx context.Context, pts []Point) error {
	tx, err := s.db.BeginTx(ctx, nil)
	if err != nil {
		return err
	}
	defer tx.Rollback()

	rows := make([]any, 0, len(pts)*4)
	rollups := map[[2]int64]*agg{}
	// Ids created in this transaction join the cache only after commit, so
	// a rollback can never leave the cache pointing at a missing row.
	ids := map[string]int64{}
	for _, p := range pts {
		key := seriesKey(p.Sensor, p.Field)
		id, ok := ids[key]
		if !ok {
			if id, err = s.lookupID(ctx, tx, p.Sensor, p.Field); err != nil {
				return err
			}
			if id == 0 {
				if _, err := tx.ExecContext(ctx, s.q(`INSERT INTO series (sensor, field) VALUES (?, ?) ON CONFLICT DO NOTHING`), p.Sensor, p.Field); err != nil {
					return err
				}
				if id, err = s.lookupID(ctx, tx, p.Sensor, p.Field); err != nil {
					return err
				}
			}
			ids[key] = id
		}
		if p.IsText {
			rows = append(rows, id, p.TS, nil, p.Text)
			continue
		}
		rows = append(rows, id, p.TS, p.Value, nil)
		k := [2]int64{id, p.TS - p.TS%60000}
		a := rollups[k]
		if a == nil {
			a = &agg{series: id, minute: k[1], min: p.Value, max: p.Value}
			rollups[k] = a
		}
		a.n++
		a.sum += p.Value
		a.sumsq += p.Value * p.Value
		a.min = min(a.min, p.Value)
		a.max = max(a.max, p.Value)
	}

	for i := 0; i < len(rows); i += rowsPerStmt * 4 {
		chunk := rows[i:min(i+rowsPerStmt*4, len(rows))]
		q := `INSERT INTO readings (series, ts, value, text) VALUES ` +
			strings.TrimSuffix(strings.Repeat("(?, ?, ?, ?),", len(chunk)/4), ",") +
			` ON CONFLICT (series, ts) DO NOTHING`
		if _, err := tx.ExecContext(ctx, s.q(q), chunk...); err != nil {
			return fmt.Errorf("insert readings: %w", err)
		}
	}

	ra := make([]any, 0, len(rollups)*7)
	for _, a := range rollups {
		ra = append(ra, a.series, a.minute, a.n, a.sum, a.sumsq, a.min, a.max)
	}
	for i := 0; i < len(ra); i += rowsPerStmt * 7 {
		chunk := ra[i:min(i+rowsPerStmt*7, len(ra))]
		q := `INSERT INTO rollup_1m AS r (series, minute, n, sum, sumsq, min, max) VALUES ` +
			strings.TrimSuffix(strings.Repeat("(?, ?, ?, ?, ?, ?, ?),", len(chunk)/7), ",") +
			` ON CONFLICT (series, minute) DO UPDATE SET
			  n = r.n + excluded.n, sum = r.sum + excluded.sum, sumsq = r.sumsq + excluded.sumsq,
			  min = CASE WHEN excluded.min < r.min THEN excluded.min ELSE r.min END,
			  max = CASE WHEN excluded.max > r.max THEN excluded.max ELSE r.max END`
		if _, err := tx.ExecContext(ctx, s.q(q), chunk...); err != nil {
			return fmt.Errorf("upsert rollups: %w", err)
		}
	}
	if err := tx.Commit(); err != nil {
		return err
	}
	s.mu.Lock()
	for k, id := range ids {
		s.series[k] = id
	}
	s.mu.Unlock()
	return nil
}

func (s *sqlDB) SaveEvent(ctx context.Context, e anomaly.Event) error {
	var end any
	if e.End > 0 {
		end = e.End
	}
	_, err := s.db.ExecContext(ctx, s.q(`INSERT INTO anomalies (id, sensor, field, kind, start_ts, end_ts, value, score, message)
		VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?)
		ON CONFLICT (id) DO UPDATE SET end_ts = excluded.end_ts`),
		e.ID, e.Sensor, e.Field, e.Kind, e.Start, end, e.Value, e.Score, e.Message)
	return err
}

func (s *sqlDB) CloseOpenEvents(ctx context.Context, at int64) error {
	_, err := s.db.ExecContext(ctx, s.q(`UPDATE anomalies SET end_ts = ? WHERE end_ts IS NULL`), at)
	return err
}

func (s *sqlDB) Series(ctx context.Context, sensor, field string, from, to, bucket int64) ([]Bucket, error) {
	id, err := s.lookupID(ctx, s.db, sensor, field)
	if err != nil || id == 0 {
		return []Bucket{}, err
	}
	var q string
	if bucket >= 60000 && bucket%60000 == 0 {
		q = `SELECT (minute / ?) * ? AS b, CAST(SUM(n) AS BIGINT), MIN(min), MAX(max), CAST(SUM(sum) AS DOUBLE PRECISION) / CAST(SUM(n) AS DOUBLE PRECISION)
		     FROM rollup_1m WHERE series = ? AND minute >= ? AND minute < ? GROUP BY b ORDER BY b`
		from -= from % 60000 // include the minute containing from
	} else {
		q = `SELECT (ts / ?) * ? AS b, COUNT(value), MIN(value), MAX(value), AVG(value)
		     FROM readings WHERE series = ? AND ts >= ? AND ts < ? AND value IS NOT NULL GROUP BY b ORDER BY b`
	}
	rows, err := s.db.QueryContext(ctx, s.q(q), bucket, bucket, id, from, to)
	if err != nil {
		return nil, err
	}
	defer rows.Close()
	out := []Bucket{}
	for rows.Next() {
		var b Bucket
		if err := rows.Scan(&b.T, &b.N, &b.Min, &b.Max, &b.Avg); err != nil {
			return nil, err
		}
		out = append(out, b)
	}
	return out, rows.Err()
}

// Stats over short windows reads raw rows (exact); longer windows read
// rollups at minute resolution, which is ~cheaper by the sample rate x 60.
func (s *sqlDB) Stats(ctx context.Context, sensor, field string, from, to int64) (Stats, error) {
	id, err := s.lookupID(ctx, s.db, sensor, field)
	if err != nil || id == 0 {
		return Stats{}, err
	}
	q := `SELECT COUNT(value), COALESCE(SUM(value), 0), COALESCE(SUM(value * value), 0), MIN(value), MAX(value)
	      FROM readings WHERE series = ? AND ts >= ? AND ts < ? AND value IS NOT NULL`
	if to-from > 6*3600*1000 {
		q = `SELECT CAST(COALESCE(SUM(n), 0) AS BIGINT), COALESCE(SUM(sum), 0), COALESCE(SUM(sumsq), 0), MIN(min), MAX(max)
		     FROM rollup_1m WHERE series = ? AND minute >= ? AND minute < ?`
		from -= from % 60000
	}
	var n int64
	var sum, sumsq float64
	var mn, mx sql.NullFloat64
	if err := s.db.QueryRowContext(ctx, s.q(q), id, from, to).Scan(&n, &sum, &sumsq, &mn, &mx); err != nil {
		return Stats{}, err
	}
	return StatsFromSums(n, sum, sumsq, mn.Float64, mx.Float64), nil
}

func (s *sqlDB) Events(ctx context.Context, eq EventQuery) ([]anomaly.Event, error) {
	q := `SELECT id, sensor, field, kind, start_ts, COALESCE(end_ts, 0), COALESCE(value, 0), COALESCE(score, 0), COALESCE(message, '')
	      FROM anomalies WHERE start_ts >= ? AND start_ts < ?`
	args := []any{eq.From, eq.To}
	if eq.Sensor != "" {
		q += ` AND sensor = ?`
		args = append(args, eq.Sensor)
	}
	if eq.ActiveOnly {
		q += ` AND end_ts IS NULL`
	}
	if eq.Limit <= 0 || eq.Limit > 1000 {
		eq.Limit = 1000
	}
	q += ` ORDER BY start_ts DESC LIMIT ?`
	args = append(args, eq.Limit)
	rows, err := s.db.QueryContext(ctx, s.q(q), args...)
	if err != nil {
		return nil, err
	}
	defer rows.Close()
	out := []anomaly.Event{}
	for rows.Next() {
		var e anomaly.Event
		if err := rows.Scan(&e.ID, &e.Sensor, &e.Field, &e.Kind, &e.Start, &e.End, &e.Value, &e.Score, &e.Message); err != nil {
			return nil, err
		}
		out = append(out, e)
	}
	return out, rows.Err()
}

func (s *sqlDB) Prune(ctx context.Context, rawBefore, rollupBefore, eventsBefore int64) error {
	ids := []int64{}
	rows, err := s.db.QueryContext(ctx, `SELECT id FROM series`)
	if err != nil {
		return err
	}
	for rows.Next() {
		var id int64
		if err := rows.Scan(&id); err != nil {
			rows.Close()
			return err
		}
		ids = append(ids, id)
	}
	rows.Close()
	// Per-series deletes walk the (series, ts) primary key instead of
	// scanning the whole table.
	for _, id := range ids {
		if rawBefore > 0 {
			if _, err := s.db.ExecContext(ctx, s.q(`DELETE FROM readings WHERE series = ? AND ts < ?`), id, rawBefore); err != nil {
				return err
			}
		}
		if rollupBefore > 0 {
			if _, err := s.db.ExecContext(ctx, s.q(`DELETE FROM rollup_1m WHERE series = ? AND minute < ?`), id, rollupBefore); err != nil {
				return err
			}
		}
	}
	if eventsBefore > 0 {
		if _, err := s.db.ExecContext(ctx, s.q(`DELETE FROM anomalies WHERE start_ts < ? AND end_ts IS NOT NULL`), eventsBefore); err != nil {
			return err
		}
	}
	return nil
}
